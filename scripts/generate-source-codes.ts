#!/usr/bin/env bun
/**
 * Regenerates lib/source-codes.ts from the playground component files, so the
 * docs always show the source that actually ships. Run after editing a
 * component: bun run gen:sources
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const COMPONENTS = {
  customKeyboardSourceCode: "custom-keyboard.tsx",
  aiImageCardSourceCode: "ai-image-card.tsx",
  loaderAnimationSourceCode: "loader-animation.tsx",
  searchBarSourceCode: "search-bar.tsx",
} as const;

const dir = path.join(process.cwd(), "components", "ui");

const entries = Object.entries(COMPONENTS).map(([name, file]) => {
  const src = readFileSync(path.join(dir, file), "utf8").trimEnd();
  return `export const ${name} = ${JSON.stringify(src)};`;
});

const out = [
  "// Generated by scripts/generate-source-codes.ts - do not edit by hand.",
  "// Run `bun run gen:sources` after changing a playground component.",
  "",
  ...entries,
  "",
].join("\n");

writeFileSync(path.join(process.cwd(), "lib", "source-codes.ts"), out);
console.log(`Wrote lib/source-codes.ts (${entries.length} components)`);
